#!/usr/bin/env python
"""Table 5 from results-e17b: what one real-model update actually costs.

    python tb5_e17.py            # markdown to stdout
    python tb5_e17.py --latex    # also writes paper/generated/tb5.tex

Figure F9 gives the placement ratio; this table gives absolute generation time.
Only clean records are eligible. A comparison requires both placements to have
eligible records. If both fit, report the faster; if one fits, report its time;
if neither fits, report OOM. Excluded or missing records are shown as dashes.
"""
from __future__ import annotations

import argparse
from e17_data import cell
from pathlib import Path

HERE = Path(__file__).resolve().parent

ARMS = [("mirrored_seed", "seed, mirrored"), ("mirrored_lr1", "rank 1"),
        ("mirrored_lr4", "rank 4"), ("mirrored_lr16", "rank 16")]
POPULATIONS = (32, 64, 128, 240)
DEVICES = (2, 4, 8)



def best(strategy: str, n: int, d: int) -> str:
    """The faster placement in ms, or OOM when neither fits."""
    pair = (cell(strategy, "A", n, d), cell(strategy, "B", n, d))
    if None in pair:
        return "--"
    times = [t for t in pair if isinstance(t, float)]
    if times:
        return f"{min(times) * 1e3:.0f}"
    return "OOM"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    args = ap.parse_args(argv)

    rows = []
    for strategy, label in ARMS:
        for n in POPULATIONS:
            rows.append((label, n, [best(strategy, n, d) for d in DEVICES]))

    print("| variant | N | D=2 | D=4 | D=8 |")
    print("|---|---|---|---|---|")
    for label, n, vals in rows:
        print(f"| {label} | {n} | " + " | ".join(vals) + " |")

    if args.latex:
        out = HERE.parent.parent / "paper" / "generated" / "tb5.tex"
        body = [f"{label} & {n} & " + " & ".join(vals) + r" \\"
                for label, n, vals in rows]
        out.write_text("\n".join([
            "% generated by experiments/countdown/tb5_e17.py --latex; do not edit",
            r"\begin{table*}[t]", r"\centering", r"\small",
            r"\caption{What one real-model update costs, in ms (Qwen2.5-0.5B, one "
            r"generation (evaluate, then update) on the fixed prompt batch, TPU v5e-8, "
            r"median of five repeats). Each entry is the faster placement (split for full rank at multiple devices, replicated for low rank); "
            r"Figure~\ref{fig:f9} gives the ratio between them. OOM: neither placement "
            r"fits a 16\,GB chip at that shape. Dashes mean a comparison lacks two clean "
            r"records, not a memory failure. All one-device records are excluded.}",
            r"\label{tab:tb5}",
            r"\begin{tabular}{llrrr}", r"\toprule",
            r"variant & $N$ & $D{=}2$ & $D{=}4$ & $D{=}8$ \\",
            r"\midrule",
            *body,
            r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]))
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
