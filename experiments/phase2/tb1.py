#!/usr/bin/env python
"""TB1, the baseline throughput table, assembled from the committed M4 runs.

    python tb1.py             # markdown to stdout
    python tb1.py --latex     # also writes ../../paper/generated/tb1.tex

Sources: `results-m4-a100-run2` (GPU) and `results-m4-tpu-v5e8` (TPU), the runs
whose READMEs and docs/03 M4 describe the protocol. D=1 is the like-for-like
comparison (none of the references shards, so at D=8 they idle seven devices);
the D=8 shardes rows are reported separately as what sharding adds, never as a
ratio against an unsharded arm. Failed arms render as entries, not absences:
an OOM is a result (on the v5e it is the ravel_pytree foreclosure, measured).

Token-position evaluations per second, tokens = population * batch * seq: the unit both papers report
and the only one that survives comparing different population sizes.
"""

from __future__ import annotations

import argparse
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent

#: Per platform, in preference order: the first directory holding m4-d{D}.json
#: wins. The A100 D=1 rerun lives in run2; its D=8 rows are in results-m4.
SOURCES = [
    ("A100", [HERE / "results-m4-a100-run2", HERE / "results-m4"]),
    ("TPU v5e", [HERE / "results-m4-tpu-v5e8"]),
]
#: Presentation order: our arms, then the references.
ARMS = ["shardes/mirrored_lr1/B", "shardes/seed_regenerated/B", "eggroll/rank1",
        "naive_es", "evosax/Open_ES"]
#: The D=8 table drops the references. They have no sharding path, so their
#: rows there either repeat their own D=1 rows (v5e, identical in three cells)
#: or are dashes (A100, not rerun): 20 of 24 reference cells restated Table 1
#: and the other 4 were empty. What sharding adds is the two arms that shard.
SHARDED_ARMS = ["shardes/mirrored_lr1/B", "shardes/seed_regenerated/B"]


def rows_for(paths: list[pathlib.Path], devices: int) -> dict:
    f = next((p / f"m4-d{devices}.json" for p in paths
              if (p / f"m4-d{devices}.json").exists()), None)
    if f is None:
        return {}
    out = {}
    for row in json.loads(f.read_text())["rows"]:
        key = (row["d_model"], row["population"], row["arm"])
        if "tokens_per_second" in row:
            out[key] = (row["tokens_per_second"], row["sharded"])
        else:
            out[key] = ("OOM", False)
    return out


def fmt(v) -> str:
    if v == "OOM":
        return "OOM"
    if v is None:
        return "--"
    return f"{v / 1e6:.2f}M" if v >= 1e6 else f"{v / 1e3:.0f}k"


def build(devices: int):
    """[(shape, {platform: {arm: value}})], shapes present in any source."""
    per = {name: rows_for(p, devices) for name, p in SOURCES}
    shapes = sorted({(k[0], k[1]) for r in per.values() for k in r})
    table = []
    for d, n in shapes:
        cell = {name: {a: (r.get((d, n, a)) or [None])[0] for a in ARMS}
                for name, r in per.items()}
        table.append(((d, n), cell))
    return table


def markdown() -> list[str]:
    lines = []
    for devices, title in ((1, "TB1: token-position evaluations/s at D=1 (like-for-like; no reference shards)"),
                           (8, "TB1b: D=8, what sharding adds (references idle 7 devices; not a ratio)")):
        lines += [f"**{title}**", "",
                  "| shape | platform | " + " | ".join(a.split("/")[-2 if a.startswith("shardes") else -1] if "/" in a else a for a in ARMS) + " |",
                  "|---|---|" + "---|" * len(ARMS)]
        for (d, n), cell in build(devices):
            for name, vals in cell.items():
                lines.append(f"| d={d}, N={n} | {name} | "
                             + " | ".join(fmt(vals[a]) for a in ARMS) + " |")
        lines.append("")
    return lines


def latex() -> str:
    """One table: the library's two arms at D=1 and D=8, the references at D=1 only.

    None of the references has a sharding path, so their D=8 figure is their D=1 figure
    (on the v5e the reruns reproduced it; on the A100 they were not rerun). Printing it
    twice would suggest a comparison that is not there.
    """
    one, eight = build(1), dict(build(8))
    cols = [("shardes/mirrored_lr1/B", 1), ("shardes/mirrored_lr1/B", 8), ("eggroll/rank1", 1),
            ("shardes/seed_regenerated/B", 1), ("shardes/seed_regenerated/B", 8),
            ("naive_es", 1), ("evosax/Open_ES", 1)]
    out = ["% generated by experiments/phase2/tb1.py; do not edit by hand",
           "\\begin{table*}[t]", "\\centering", "\\small", "\\setlength{\\tabcolsep}{5pt}",
           "\\caption{Throughput at matched shapes: token-position evaluations per second "
           "(tokens = population $\\times$ batch $\\times$ sequence). \\emph{rank 1} and "
           "\\emph{seed} are this library's variants; \\emph{EGGROLL} is its authors' released "
           "code; \\emph{naive} gives every member its own copy of the weights, evaluating the population in parallel; \\emph{evosax} is OpenES in the incumbent JAX library. "
           "None of the three references shards, so only the library's variants have a $D{=}8$ "
           "column. Seed evaluates one candidate at a time to keep weight memory at $O(P)$. "
           "Qiu et al.'s released code is not included. OOM: does not fit the "
           "device at this shape.}",
           "\\label{tab:tb1}",
           "\\begin{tabular}{llrrrrrrr}", "\\toprule",
           " & & \\multicolumn{2}{c}{rank 1} & EGGROLL & \\multicolumn{2}{c}{seed} "
           "& naive & evosax \\\\",
           "\\cmidrule(lr){3-4}\\cmidrule(lr){6-7}",
           "shape & platform & $D{=}1$ & $D{=}8$ & $D{=}1$ & $D{=}1$ & $D{=}8$ & $D{=}1$ "
           "& $D{=}1$ \\\\",
           "\\midrule"]
    for (d, n), cell in one:
        for name, vals in cell.items():
            sharded = eight.get((d, n), {}).get(name, {})
            entries = [fmt(vals[a] if dev == 1 else sharded.get(a)) for a, dev in cols]
            out.append(f"$d{{=}}{d}$, $N{{=}}{n}$ & {name} & " + " & ".join(entries) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(out)


def ratios() -> list[str]:
    """The ratios the text quotes, per platform, over the four shapes."""
    one, eight = build(1), dict(build(8))
    pairs = [("rank 1 vs EGGROLL code, both D=1", "shardes/mirrored_lr1/B", 1, "eggroll/rank1"),
             ("rank 1 at D=8 vs EGGROLL code at D=1", "shardes/mirrored_lr1/B", 8, "eggroll/rank1"),
             ("seed vs naive, both D=1", "shardes/seed_regenerated/B", 1, "naive_es")]
    out = []
    for label, arm, dev, ref in pairs:
        for name, _ in SOURCES:
            rs = []
            for (d, n), cell in one:
                num = (cell[name][arm] if dev == 1 else eight.get((d, n), {}).get(name, {}).get(arm))
                den = cell[name][ref]
                if isinstance(num, float) and isinstance(den, float):
                    rs.append(num / den)
            if rs:
                out.append(f"{label}, {name}: {min(rs):.2f} to {max(rs):.2f}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--latex", action="store_true")
    args = ap.parse_args()
    print("\n".join(markdown()))
    print("\n".join(ratios()))
    if args.latex:
        dest = HERE.parent.parent / "paper" / "generated" / "tb1.tex"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(latex())
        print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
